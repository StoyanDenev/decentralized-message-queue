static void check_vector(const uint8_t seed[32], const uint8_t pk[32],
                         const uint8_t *message, size_t length,
                         const uint8_t expected[64], bool deny) {
    uint8_t signature[64], derived[32], changed[1024], bad[64], bad_pk[32];
    size_t count=length<=448u?0u:1u;
    CHECK(length<=sizeof changed);
    reset_allocator(deny,false);
    determ_ed25519_pubkey_from_seed(seed,derived);
    CHECK(!memcmp(derived,pk,32)); allocation_result(0,0,0);
    reset_allocator(deny,true);
    CHECK(determ_ed25519_sign(seed,pk,message,length,signature)==0);
    CHECK(!memcmp(signature,expected,64)); allocation_result(count,count,64u+length);
    reset_allocator(deny,false);
    CHECK(determ_ed25519_verify(pk,message,length,expected)==0);
    allocation_result(count,count,64u+length);
    if (length) {
        memcpy(changed,message,length); changed[length-1]^=1u;
        reset_allocator(deny,false);
        CHECK(determ_ed25519_verify(pk,changed,length,expected)!=0);
        allocation_result(count,count,64u+length);
    }
    memcpy(bad,expected,64); bad[0]^=1u;
    reset_allocator(deny,false);
    CHECK(determ_ed25519_verify(pk,message,length,bad)!=0);
    allocation_result(count,count,64u+length);
    /* Scalar and public-key canonicality still reject before allocation. */
    memcpy(bad,expected,64); memset(bad+32,0xff,32);
    reset_allocator(deny,false);
    CHECK(determ_ed25519_verify(pk,message,length,bad)!=0);
    allocation_result(0,0,0);
    memset(bad_pk,0xff,32); bad_pk[0]=0xed; bad_pk[31]=0x7f;
    reset_allocator(deny,false);
    CHECK(determ_ed25519_verify(bad_pk,message,length,expected)!=0);
    allocation_result(0,0,0);
}
static void check_failure(const uint8_t seed[32], const uint8_t pk[32],
                          const uint8_t *message, size_t length,
                          const uint8_t expected[64], bool overflow) {
    uint8_t signature[64], before[64];
    size_t count=overflow?0u:1u;
    memset(signature,0xa5,sizeof signature); memcpy(before,signature,sizeof before);
    reset_allocator(true,true);
    CHECK(determ_ed25519_sign(seed,pk,message,length,signature)==-1);
    CHECK(!memcmp(signature,before,sizeof signature));
    allocation_result(count,0,overflow?0u:64u+length);
    reset_allocator(true,false);
    CHECK(determ_ed25519_verify(pk,message,length,expected)==-1);
    allocation_result(count,0,overflow?0u:64u+length);
}
int main(void) {
    uint8_t seed[32], message[1024];
    for (size_t i=0;i<sizeof rfc_vectors/sizeof rfc_vectors[0];i++) {
        check_vector(rfc_vectors[i].seed,rfc_vectors[i].public_key,
                     rfc_vectors[i].length?rfc_vectors[i].message:NULL,
                     rfc_vectors[i].length,rfc_vectors[i].signature,true);
    }
    for (size_t i=0;i<sizeof seed;i++) seed[i]=(uint8_t)i;
    for (size_t i=0;i<sizeof message;i++) message[i]=(uint8_t)(17u*i+3u);
    for (size_t i=0;i<sizeof boundary_vectors/sizeof boundary_vectors[0];i++) {
        size_t length=boundary_vectors[i].length;
        const uint8_t *expected=boundary_vectors[i].signature;
        check_vector(seed,boundary_public_key,message,length,expected,false);
        if (length<=448u) check_vector(seed,boundary_public_key,message,length,expected,true);
        else check_failure(seed,boundary_public_key,message,length,expected,false);
    }
    /* At the final representable size allocation is attempted, then fails;
     * above it refusal precedes allocation and any message dereference. */
    check_failure(seed,boundary_public_key,NULL,SIZE_MAX-64u,boundary_vectors[0].signature,false);
    check_failure(seed,boundary_public_key,NULL,SIZE_MAX-63u,boundary_vectors[0].signature,true);
    check_failure(seed,boundary_public_key,NULL,SIZE_MAX,boundary_vectors[0].signature,true);
    puts("PASS: bounded Ed25519 allocation, fixed signature bytes and rejection boundaries");
    return 0;
}
