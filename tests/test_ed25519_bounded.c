#define CHECK(condition) do { if (!(condition)) { \
    fprintf(stderr,"FAIL: %s:%d: %s\n",__FILE__,__LINE__,#condition); \
    exit(EXIT_FAILURE); } } while (0)

static size_t allocations, frees, requested;
static void *outstanding;
static bool deny_allocation, require_wipe;

void *test_ed25519_malloc(size_t size) {
    CHECK(outstanding==NULL);
    allocations++; requested=size;
    if (deny_allocation) return NULL;
    outstanding=malloc(size);
    CHECK(outstanding!=NULL);
    return outstanding;
}
void test_ed25519_free(void *pointer) {
    /* Detect an automatic-buffer free without passing it to the system heap. */
    CHECK(pointer!=NULL && pointer==outstanding);
    if (require_wipe) {
        const uint8_t *bytes=(const uint8_t *)pointer;
        for (size_t i=0;i<requested;i++) CHECK(bytes[i]==0);
    }
    frees++; free(pointer); outstanding=NULL;
}
static void reset_allocator(bool deny, bool wipe) {
    CHECK(outstanding==NULL);
    allocations=0; frees=0; requested=0;
    deny_allocation=deny; require_wipe=wipe;
}
static void allocation_result(size_t count, size_t freed, size_t size) {
    CHECK(allocations==count && frees==freed && outstanding==NULL);
    CHECK(requested==(count?size:0));
}

