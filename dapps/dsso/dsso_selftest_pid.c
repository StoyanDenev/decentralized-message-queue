/* ── section 1: the bounded base64url decoder ─────────────────────────────── */
static void test_b64url(void) {
    uint8_t out[64];
    size_t n = 0;
    printf("\n-- base64url (RFC 4648 §5, unpadded; strict + canonical) --\n");
    CHECK(dsso_b64url_decode(S("QQ"), out, sizeof out, &n) == DSSO_OK && n == 1 && out[0] == 'A',
          "b64url: a two-character group decodes to one byte");
    CHECK(dsso_b64url_decode(S("QUJD"), out, sizeof out, &n) == DSSO_OK && n == 3 &&
          !memcmp(out, "ABC", 3),
          "b64url: a full group decodes to three bytes");
    CHECK(dsso_b64url_decode(S("QR"), out, sizeof out, &n) == DSSO_E_FORMAT,
          "b64url: a NON-CANONICAL tail (unused bits set) is rejected");
    CHECK(dsso_b64url_decode(S("QUJ="), out, sizeof out, &n) == DSSO_E_FORMAT,
          "b64url: '=' padding is rejected (JOSE is unpadded)");
    CHECK(dsso_b64url_decode(S("QQ+/"), out, sizeof out, &n) == DSSO_E_FORMAT,
          "b64url: the standard alphabet's '+' and '/' are rejected");
    CHECK(dsso_b64url_decode(S("Q"), out, sizeof out, &n) == DSSO_E_FORMAT,
          "b64url: a length of 1 mod 4 encodes nothing and is rejected");
    CHECK(dsso_b64url_decode(S("QQ QQ"), out, sizeof out, &n) == DSSO_E_FORMAT,
          "b64url: embedded whitespace is rejected");
    CHECK(dsso_b64url_decode(S("QUJDRA"), out, 2, &n) == DSSO_E_ARG,
          "b64url: an output that would exceed the cap is refused, not truncated");
    out[0] = 0xAA;
    CHECK(dsso_b64url_decode(S("QR"), out, sizeof out, &n) == DSSO_E_FORMAT && out[0] == 0xAA,
          "b64url: the output buffer is untouched on failure");
    CHECK(dsso_b64url_decode(S(""), out, sizeof out, &n) == DSSO_OK && n == 0,
          "b64url: an empty input decodes to zero bytes");
}

/* ── section 2: the bounded JSON reader ───────────────────────────────────── */
static const char FUZZ_JSON[] =
    "{\"iss\":\"https://pid.example\",\"n\":[1,2,{\"b\":null}],"
    "\"e\":\"\\u00e9\\ud83d\\ude00\",\"d\":-12.5e3,\"t\":true}";

static void test_json(void) {
    dsso_slice root, v;
    dsso_json_type t;
    int64_t i64;
    uint8_t buf[64];
    size_t n = 0, cnt = 0;

    printf("\n-- bounded JSON reader (RFC 8259 subset, strict) --\n");
    CHECK(dsso_json_validate(S(FUZZ_JSON), &root, &t) == DSSO_OK && t == DSSO_JSON_OBJECT,
          "json: a well-formed document validates as an object");
    CHECK(dsso_json_member(root, "iss", &v, &t) == DSSO_OK && t == DSSO_JSON_STRING &&
          dsso_json_string_equals(v, "https://pid.example"),
          "json: a string member is found and compares by VALUE");
    CHECK(dsso_json_member(root, "n", &v, &t) == DSSO_OK && t == DSSO_JSON_ARRAY &&
          dsso_json_array_len(v, &cnt) == DSSO_OK && cnt == 3,
          "json: an array member reports its element count");
    CHECK(dsso_json_member(root, "e", &v, &t) == DSSO_OK &&
          dsso_json_string(v, buf, sizeof buf, &n) == DSSO_OK && n == 2 + 4,
          "json: \\u escapes and a surrogate pair decode to UTF-8");
    CHECK(dsso_json_member(root, "d", &v, &t) == DSSO_OK && t == DSSO_JSON_NUMBER &&
          dsso_json_int(v, &i64) == DSSO_E_FORMAT,
          "json: a non-integer number is refused where an integer is required");
    CHECK(dsso_json_member(root, "absent", &v, &t) == DSSO_E_FORMAT,
          "json: an absent member is a failure, never a zero value");

    CHECK(dsso_json_validate(S("{\"a\":1,\"a\":2}"), &root, &t) == DSSO_E_FORMAT,
          "json: a DUPLICATE member name is rejected, not resolved");
    CHECK(dsso_json_validate(S("{\"a\":1,\"\\u0061\":2}"), &root, &t) == DSSO_E_FORMAT,
          "json: a duplicate hidden behind a \\u escape is still a duplicate");
    CHECK(dsso_json_validate(S("{\"a\":1} trailing"), &root, &t) == DSSO_E_FORMAT,
          "json: trailing data after the top-level value is rejected");
    CHECK(dsso_json_validate(S("{\"a\":1}{\"b\":2}"), &root, &t) == DSSO_E_FORMAT,
          "json: a second top-level value is trailing data");
    CHECK(dsso_json_validate(S("[[[[[[[[[[1]]]]]]]]]]"), &root, &t) == DSSO_E_FORMAT,
          "json: nesting past the fixed depth cap is rejected");
    CHECK(dsso_json_validate(S("[[[[1]]]]"), &root, &t) == DSSO_OK,
          "json: nesting within the depth cap is accepted");
    CHECK(dsso_json_validate(S("{\"a\":01}"), &root, &t) == DSSO_E_FORMAT,
          "json: a leading zero is not an RFC 8259 number");
    CHECK(dsso_json_validate(S("{\"a\":+1}"), &root, &t) == DSSO_E_FORMAT,
          "json: a leading '+' is not an RFC 8259 number");
    CHECK(dsso_json_validate(S("{\"a\":NaN}"), &root, &t) == DSSO_E_FORMAT,
          "json: NaN / Infinity are rejected");
    CHECK(dsso_json_validate(S("{\"a\":\"x\ty\"}"), &root, &t) == DSSO_E_FORMAT,
          "json: a raw control character inside a string is rejected");
    CHECK(dsso_json_validate(S("{\"a\":\"\\q\"}"), &root, &t) == DSSO_E_FORMAT,
          "json: an unknown escape is rejected");
    CHECK(dsso_json_validate(S("{\"a\":\"\\ud83d\"}"), &root, &t) == DSSO_E_FORMAT,
          "json: an unpaired surrogate is rejected");
    CHECK(dsso_json_validate(S("{\"a\":1,}"), &root, &t) == DSSO_E_FORMAT,
          "json: a trailing comma is rejected");
    CHECK(dsso_json_validate(S("{'a':1}"), &root, &t) == DSSO_E_FORMAT,
          "json: single-quoted names are rejected");
    CHECK(dsso_json_validate(S("{\"a\":1 /*c*/}"), &root, &t) == DSSO_E_FORMAT,
          "json: comments are rejected");
    {
        /* One element past DSSO_JSON_MAX_ELEMS. */
        static char big[DSSO_JSON_MAX_ELEMS * 2 + 8];
        size_t k, o = 0;
        big[o++] = '[';
        for (k = 0; k <= DSSO_JSON_MAX_ELEMS; ++k) { big[o++] = '1'; big[o++] = ','; }
        big[o - 1] = ']';
        CHECK(dsso_json_validate(SB((const uint8_t *)big, o), &root, &t) == DSSO_E_FORMAT,
              "json: a container past the element cap is rejected");
    }
    CHECK(dsso_json_validate(S("{\"a\":9223372036854775808}"), &root, &t) == DSSO_OK &&
          dsso_json_member(root, "a", &v, &t) == DSSO_OK &&
          dsso_json_int(v, &i64) == DSSO_E_FORMAT,
          "json: an integer past int64 range is refused rather than wrapped");
}

/* ── section 3: ES256 over P-256, composed on the shipped stack ───────────── */
static void test_es256(void) {
    uint8_t sig[64], pk[65];
    printf("\n-- ES256 (RFC 7515 §3.4) on determ::c99 P-256 --\n");
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), KAT_SIG_SAMPLE) == DSSO_OK,
          "es256: RFC 6979 A.2.5 'sample' KAT verifies (external anchor)");
    CHECK(dsso_es256_verify(KAT_PK, S("test"), KAT_SIG_TEST) == DSSO_OK,
          "es256: RFC 6979 A.2.5 'test' KAT verifies (external anchor)");
    CHECK(dsso_es256_verify(KAT_PK, S("sampla"), KAT_SIG_SAMPLE) == DSSO_E_CRYPTO,
          "es256: a one-byte change to the message is rejected");
    memcpy(sig, KAT_SIG_SAMPLE, 64); sig[63] ^= 1;
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_CRYPTO,
          "es256: a one-bit change to s is rejected");
    memcpy(sig, KAT_SIG_SAMPLE, 64); sig[0] ^= 1;
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_CRYPTO,
          "es256: a one-bit change to r is rejected");
    memset(sig, 0, 64); memcpy(sig + 32, KAT_SIG_SAMPLE + 32, 32);
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_FORMAT,
          "es256: r == 0 is a non-canonical scalar, rejected before any arithmetic");
    memcpy(sig, KAT_SIG_SAMPLE, 64); memset(sig + 32, 0, 32);
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_FORMAT,
          "es256: s == 0 is a non-canonical scalar");
    memcpy(sig, KAT_SIG_SAMPLE, 64); memset(sig, 0xFF, 32);
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_FORMAT,
          "es256: r >= n is a non-canonical scalar");
    memcpy(sig, KAT_SIG_SAMPLE, 64); memset(sig + 32, 0xFF, 32);
    CHECK(dsso_es256_verify(KAT_PK, S("sample"), sig) == DSSO_E_FORMAT,
          "es256: s >= n is a non-canonical scalar");
    memcpy(pk, KAT_PK, 65); pk[64] ^= 1;
    CHECK(dsso_es256_verify(pk, S("sample"), KAT_SIG_SAMPLE) == DSSO_E_CRYPTO,
          "es256: an off-curve public key is rejected, never used");
    memcpy(pk, KAT_PK, 65); pk[0] = 0x02;
    CHECK(dsso_es256_verify(pk, S("sample"), KAT_SIG_SAMPLE) == DSSO_E_CRYPTO,
          "es256: a non-SEC1-uncompressed key encoding is rejected");
}

/* ── section 4: the bounded inflate ───────────────────────────────────────── */
static void test_inflate(void) {
    uint8_t out[DSSO_MAX_STATUS_BYTES];
    uint8_t mut[sizeof PIDV_ZLIB];
    size_t n = 0, i, rejected = 0, exact = 0, other = 0;
    printf("\n-- bounded inflate (RFC 1950/1951) --\n");
    CHECK(dsso_inflate(SB(PIDV_ZLIB, sizeof PIDV_ZLIB), out, sizeof out, &n) == DSSO_OK &&
          n == sizeof PIDV_ZLIB_PLAIN && !memcmp(out, PIDV_ZLIB_PLAIN, n),
          "inflate: the status bitstring round-trips byte-exactly");
    CHECK(dsso_inflate(SB(PIDV_ZLIB, sizeof PIDV_ZLIB), out, 2, &n) == DSSO_E_FORMAT,
          "inflate: a stream that would exceed the output cap is refused");
    CHECK(dsso_inflate(SB(PIDV_ZLIB, 4), out, sizeof out, &n) == DSSO_E_FORMAT,
          "inflate: a truncated stream is refused");
    {
        memcpy(mut, PIDV_ZLIB, sizeof mut);
        mut[sizeof mut - 1] ^= 0xFF;
        CHECK(dsso_inflate(SB(mut, sizeof mut), out, sizeof out, &n) == DSSO_E_FORMAT,
              "inflate: a wrong Adler-32 trailer is refused");
        memcpy(mut, PIDV_ZLIB, sizeof mut);
        mut[0] = 0x00;
        CHECK(dsso_inflate(SB(mut, sizeof mut), out, sizeof out, &n) == DSSO_E_FORMAT,
              "inflate: a bad zlib header is refused");
    }
    for (i = 0; i < 1500; ++i) {
        size_t k = rnd_below(sizeof mut);
        int rc;
        memcpy(mut, PIDV_ZLIB, sizeof mut);
        mut[k] = (uint8_t)(mut[k] ^ (1u << rnd_below(8)));
        n = 0xDEAD;
        rc = dsso_inflate(SB(mut, sizeof mut), out, sizeof out, &n);
        if (rc == DSSO_OK) {
            if (n == sizeof PIDV_ZLIB_PLAIN && !memcmp(out, PIDV_ZLIB_PLAIN, n)) exact++;
            else if (n <= sizeof out) other++;
            else { other++; g_fail++; }
        } else if (rc < 0 && n == 0xDEAD) {
            rejected++;
        } else {
            g_fail++;
        }
    }
    CHECK(rejected + exact + other == 1500,
          "inflate fuzz: 1500 single-bit mutants each returned a definite verdict");
    CHECK(rejected > 1000,
          "inflate fuzz: the overwhelming majority are rejected (the Adler-32 sees them)");
    printf("     [inflate fuzz: %lu rejected, %lu byte-identical, %lu other-but-bounded]\n",
           (unsigned long)rejected, (unsigned long)exact, (unsigned long)other);
}

/* ── section 5: the nine PID verification rules ───────────────────────────── */
typedef struct { const char *name; const char *text; int want; const char *note; } pid_case;

static void run_cases(const pid_case *c, size_t n, const char *nonce) {
    dsso_pid_policy pol = pol_with(nonce);
    dsso_pid_result res;
    size_t i;
    for (i = 0; i < n; ++i) {
        char msg[220];
        int rc = dsso_pid_verify(S(c[i].text), &pol, &res);
        snprintf(msg, sizeof msg, "%s -> %s (%s)", c[i].name,
                 dsso_status_name((dsso_status)c[i].want), c[i].note);
        g_checks++;
        if (rc == c[i].want) printf("  PASS: %s\n", msg);
        else {
            printf("  FAIL: %s [got %s]\n", msg, dsso_status_name((dsso_status)rc));
            g_fail++;
        }
        dsso_pid_result_scrub(&res);
    }
}

