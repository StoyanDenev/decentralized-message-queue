static int g_fail;
static int g_checks;

#define CHECK(cond, msg) do {                                  \
        g_checks++;                                            \
        if (cond) printf("  PASS: %s\n", (msg));               \
        else { printf("  FAIL: %s\n", (msg)); g_fail++; }      \
    } while (0)

static dsso_slice S(const char *s) { dsso_slice v; v.p = (const uint8_t *)s; v.n = strlen(s); return v; }
static dsso_slice SB(const uint8_t *p, size_t n) { dsso_slice v; v.p = p; v.n = n; return v; }

/* ── the injected status-token fetch, driven from fixtures ────────────────── */
static int fixture_fetch(void *ctx, const uint8_t *uri, size_t uri_len,
                         uint8_t *out, size_t cap, size_t *outlen) {
    size_t i;
    (void)ctx;
    for (i = 0; i < PIDV_N_STATUS; ++i) {
        size_t n = strlen(PIDV_STATUS_FIXTURES[i].uri);
        if (n != uri_len || memcmp(PIDV_STATUS_FIXTURES[i].uri, uri, n) != 0) continue;
        if (PIDV_STATUS_FIXTURES[i].fail) return -1;      /* unreachable list */
        n = strlen(PIDV_STATUS_FIXTURES[i].token);
        if (n > cap) return -1;
        memcpy(out, PIDV_STATUS_FIXTURES[i].token, n);
        *outlen = n;
        return 0;
    }
    return -1;
}

static dsso_trust_anchor g_anchors[3];
static dsso_trust_list   g_trust;

static void trust_init(void) {
    memset(g_anchors, 0, sizeof g_anchors);
    g_anchors[0].iss = PIDV_ISS;  g_anchors[0].kid = PIDV_KID;
    memcpy(g_anchors[0].pk, PIDV_PK_ISSUER, 65);
    g_anchors[0].max_loa = DSSO_LOA_HIGH;
    /* A second PID Provider whose anchor entry caps it at SUBSTANTIAL, so the
     * "a token cannot talk its issuer up" rule has something to bite on. */
    g_anchors[1].iss = PIDV_ISS2; g_anchors[1].kid = PIDV_KID2;
    memcpy(g_anchors[1].pk, PIDV_PK_ISSUER2, 65);
    g_anchors[1].max_loa = DSSO_LOA_SUBSTANTIAL;
    /* The status-list signer: same issuer, its own key id. */
    g_anchors[2].iss = PIDV_ISS;  g_anchors[2].kid = PIDV_KID_STATUS;
    memcpy(g_anchors[2].pk, PIDV_PK_STATUS, 65);
    g_anchors[2].max_loa = DSSO_LOA_HIGH;
    g_trust.a = g_anchors;
    g_trust.n = 3;
}

static dsso_pid_policy pol_with(const char *nonce) {
    dsso_pid_policy p;
    memset(&p, 0, sizeof p);
    p.rp_id        = PIDV_RP_ID;
    p.nonce        = (const uint8_t *)nonce;
    p.nonce_len    = strlen(nonce);
    p.now          = PIDV_NOW;
    p.max_skew     = 120;
    p.max_pres_age = 300;
    p.max_cred_age = 86400 * 365;
    p.required_loa = DSSO_LOA_HIGH;
    p.trust        = &g_trust;
    p.fetch        = fixture_fetch;
    p.fetch_ctx    = NULL;
    return p;
}

/* ── deterministic PRNG for the fuzz arms (xorshift64*, fixed seed) ───────── */
static uint64_t g_rng = 0x9E3779B97F4A7C15ull;
static uint64_t rnd(void) {
    g_rng ^= g_rng >> 12; g_rng ^= g_rng << 25; g_rng ^= g_rng >> 27;
    return g_rng * 0x2545F4914F6CDD1Dull;
}
static size_t rnd_below(size_t n) { return n ? (size_t)(rnd() % (uint64_t)n) : 0; }

