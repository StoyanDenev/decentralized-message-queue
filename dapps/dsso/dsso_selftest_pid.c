/* `determ-dsso selftest-pid` — the falsify-on-mutant gate for DSSO's
 * wallet-relying-party surface.
 *
 * WHAT THIS GATE ASSERTS, AND WHERE. Each of the nine verification rules of
 * dsso_pid.h gets an ACCEPT case and its own rejections, asserted against the
 * status code that rule returns — so removing exactly one check turns exactly
 * its own arms RED and leaves the rest green. The account-binding rules of
 * dsso_bind.h get the same treatment. Below those, the three readers that face
 * a hostile wallet (base64url, JSON, inflate) are asserted directly rather than
 * through the pipeline, because a gate on a proxy is worthless: a parser bug is
 * a parser assertion.
 *
 * THE FIXTURES are generated by an INDEPENDENT implementation (see the header
 * of dsso_pid_vectors.h) — pure-Python P-256 anchored to the RFC 6979 A.2.5
 * known-answer vectors and cross-checked against OpenSSL. In addition, the
 * ES256 verifier under test is anchored to those SAME published vectors
 * directly, in this file, so the crypto leg does not depend on the generator at
 * all.
 *
 * THE FUZZ ARMS mutate the readers' inputs thousands of times. The property is
 * a DEFINITE VERDICT WITHOUT A CRASH: every mutant either parses (and then the
 * accessors walk it without disturbing the canaries around the buffer) or is
 * rejected with a negative status. For the presentation itself the property is
 * stronger — any mutant that differs from the original byte string must be
 * REJECTED, because every byte of a presentation is covered by one of the two
 * signatures or by the sd_hash. */
